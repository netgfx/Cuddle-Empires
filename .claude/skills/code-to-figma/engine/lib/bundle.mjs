// Generates the project's runner plugin (manifest.json + ui.html + code.js) in config.runner.out.
// code.js bundles the selected build scripts as plain async functions (works even if the sandbox forbids
// eval) and, when the sandbox allows `new Function`, also runs scripts queued on the local server
// ("watch mode": open the plugin once, Claude queues scripts, they run without further clicks).
import fs from 'node:fs';
import path from 'node:path';
import { ENGINE, scriptIndex } from './config.mjs';
import { emitCode } from './emit.mjs';

export function bundle(cfg, names) {
  const idx = scriptIndex(cfg);
  const list = names?.length ? names : Object.keys(idx).sort();
  const fns = list.map((name) => `  { name: ${JSON.stringify(name)}, run: async (__runner) => {\n${emitCode(cfg, name, { embed: true })}\n  } },`);
  const runtime = fs.readFileSync(path.join(ENGINE, 'runner/runtime.js'), 'utf8')
    .replace('/*SCRIPTS*/', () => fns.join('\n')) // function replacer: scripts contain $' / $` sequences
    .replace('/*PAGES*/null', () => JSON.stringify(Object.values(cfg.figma?.pages ?? {})));
  const dir = cfg.paths.plugin;
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'code.js'), `// GENERATED by code-to-figma (cli.mjs bundle) — do not edit. Scripts: ${list.join(', ')}\n${runtime}`);
  fs.writeFileSync(path.join(dir, 'ui.html'), fs.readFileSync(path.join(ENGINE, 'runner/ui.html'), 'utf8').replaceAll('__PORT__', String(cfg.port)));
  const manifest = {
    name: cfg.runner?.pluginName ?? `${cfg.name ?? 'Project'} · Code → Figma runner`,
    id: cfg.runner?.pluginId ?? `code-to-figma-${String(cfg.name ?? 'project').toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
    api: '1.0.0', main: 'code.js', ui: 'ui.html', editorType: ['figma'], documentAccess: 'dynamic-page',
    networkAccess: { allowedDomains: ['none'], devAllowedDomains: [`http://localhost:${cfg.port}`], reasoning: 'Reports results and snapshots to, and receives queued build scripts from, the local code-to-figma server.' },
  };
  fs.writeFileSync(path.join(dir, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  const size = fs.statSync(path.join(dir, 'code.js')).size;
  console.log(`runner plugin → ${dir}\n  ${list.length} scripts (${list.join(', ')}), code.js ${(size / 1024).toFixed(0)} KB`);
  return { dir, list };
}
